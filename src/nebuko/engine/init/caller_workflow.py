"""Caller-workflow generation for ``nebuko init`` (issue #1025).

``CallerWorkflowWriter`` renders the packaged caller-workflow template and
writes it to the target repository, never silently overwriting a workflow this
command did not generate: the rendered file starts with the
``# generated by nebuko init`` marker, and only a file carrying that marker is
ever replaced.
"""

from __future__ import annotations

from enum import Enum
from importlib.resources import files
from pathlib import Path

import jinja2

MARKER = "# generated by nebuko init"


class WriteResult(Enum):
    """What ``CallerWorkflowWriter.write`` did (or refused to do)."""

    CREATED = "created"
    UPDATED = "updated"
    UNCHANGED = "unchanged"
    REFUSED = "refused"


class CallerWorkflowWriter:
    """Renders and idempotently writes the caller workflow."""

    def __init__(
        self,
        target: Path = Path(".github/workflows/nebuko-caller.yaml"),
        template_name: str = "caller_workflow.yaml.j2",
        broker_variable: str = "NEBUKO_BROKER_URL",
    ) -> None:
        self.target = target
        self.template_name = template_name
        self.broker_variable = broker_variable

    # @stub-protected: signature defined by architect — do not modify
    def render(self) -> str:
        """The workflow text, marker first, referencing ``broker_variable``."""
        source = _template_text(self.template_name)
        environment = jinja2.Environment(trim_blocks=True, keep_trailing_newline=True)
        return environment.from_string(source).render(broker_variable=self.broker_variable)

    # @stub-protected: signature defined by architect — do not modify
    def write(self, update: bool = True, dry_run: bool = False) -> WriteResult:
        """Write the workflow, or report why it was left alone."""
        rendered = self.render()
        if not self.target.exists():
            if not dry_run:
                self._write(rendered)
            return WriteResult.CREATED
        existing = self.target.read_text(encoding="utf-8")
        if existing == rendered:
            return WriteResult.UNCHANGED
        if not _is_generated(existing) or not update:
            return WriteResult.REFUSED
        if not dry_run:
            self._write(rendered)
        return WriteResult.UPDATED

    def _write(self, text: str) -> None:
        self.target.parent.mkdir(parents=True, exist_ok=True)
        self.target.write_text(text, encoding="utf-8")


def _is_generated(text: str) -> bool:
    """Whether ``text`` starts with the marker line this command writes."""
    return text.splitlines()[:1] == [MARKER]


def _template_text(name: str) -> str:
    resource = files("nebuko.engine.init").joinpath("templates", name)
    return resource.read_text(encoding="utf-8")
