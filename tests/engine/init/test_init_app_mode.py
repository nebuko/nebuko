def test_given_the_app_is_installed_when_init_runs_end_to_end_then_no_pat_is_needed(
    monkeypatch, tmp_path, capsys
):
    """The production collaborators, not fakes: detection → variable → workflow."""
    from nebuko.engine.init.app_installation import AppInstallationResolver
    from nebuko.engine.init.caller_workflow import CallerWorkflowWriter
    from nebuko.engine.init.repo_variables import RepoVariableWriter

    class InstalledClient:
        def __init__(self):
            self.variables: dict[str, str] = {}

        def call(self, args, **kwargs):
            from nebuko.engine.lib.github_client import ApiCallResult

            joined = " ".join(args)
            if joined.endswith("/installation"):
                return ApiCallResult(
                    ok=True, status=200, payload='{"id": 4711}', error_kind=None, detail=""
                )
            if "--method" in args:
                import json

                payload = json.loads(kwargs.get("input_data") or "{}")
                self.variables[payload["name"]] = payload["value"]
                return ApiCallResult(ok=True, status=201, payload="", error_kind=None, detail="")
            return ApiCallResult(ok=False, status=404, payload="", error_kind=None, detail="")

    client = InstalledClient()
    workflow = CallerWorkflowWriter(target=tmp_path / "nebuko-caller.yaml")
    context = SetupContext(
        source=FileTemplateSource(REPO_ROOT),
        refs=StaticRefResolver(PIN),
        host=FakeHost(),
        resolver=AppInstallationResolver(client, "acme", "widgets", "nebuko"),
        variable_writer=RepoVariableWriter(client, "acme", "widgets"),
        workflow_writer=workflow,
        broker_url=BROKER,
    )
    monkeypatch.setattr(cli, "build_setup", lambda **kwargs: context)
    _set_secrets(monkeypatch, OPENROUTER_API_KEY="key-123")

    assert cli.main(["--repo", "acme/widgets", "--non-interactive"]) == 0

    assert client.variables == {}  # no repo variable: the workflow ships the default
    assert workflow.target.read_text(encoding="utf-8").startswith("# generated by nebuko init")
    assert "personal-access-tokens" not in capsys.readouterr().out
