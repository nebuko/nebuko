"""App-aware ``nebuko init`` flow (issue #1025).

Given the Nebuko App is installed, when ``init`` runs then no PAT prompt is
shown and the caller workflow is written. Without the App, ``init`` exits with
the App-install guidance (or a ``--pat`` run keeps the PAT path).
"""

from __future__ import annotations

from pathlib import Path

from nebuko.engine.init import cli
from nebuko.engine.init.caller_workflow import WriteResult
from nebuko.engine.init.ports import PreflightReport, SetupTarget
from nebuko.engine.init.refs import StaticRefResolver
from nebuko.engine.init.setup import DEFAULT_BROKER_URL, SetupContext
from nebuko.engine.init.sources import FileTemplateSource

REPO_ROOT = Path(__file__).resolve().parents[3]
PIN = "v1.2.3"
PR_URL = "https://github.com/acme/widgets/pull/7"
BROKER = "https://broker.example"


class FakeHost:
    def __init__(self):
        self.prs: list[dict] = []
        self.secrets: dict[str, str] = {}

    def gh_available(self):
        return True

    def preflight(self, target):
        return PreflightReport(ok=True, missing_scopes=(), remediation="")

    def app_installed(self, target):
        return False

    def existing_paths(self, target, paths):
        return set()

    def existing_secrets(self, target):
        return frozenset()

    def open_pr(self, target, branch, title, body, files):
        self.prs.append({"files": files, "body": body})
        return PR_URL

    def set_secret(self, target, name, value):
        self.secrets[name] = value


class FakeResolver:
    def __init__(self, installed: bool):
        self.installed = installed
        self.probes = 0

    def is_installed(self):
        self.probes += 1
        return self.installed

    def installation_id(self):
        return 4711 if self.installed else None


class FakeVariableWriter:
    def __init__(self):
        self.values: dict[str, str] = {}

    def get(self, name):
        return self.values.get(name)

    def set(self, name, value):
        self.values[name] = value


class FakeWorkflowWriter:
    def __init__(self, result=WriteResult.CREATED):
        self.result = result
        self.calls: list[dict] = []
        self.target = Path(".github/workflows/nebuko-caller.yaml")

    def render(self):
        return "# generated by nebuko init\n"

    def write(self, update=True, dry_run=False):
        self.calls.append({"update": update, "dry_run": dry_run})
        return self.result


class FakePrompter:
    def __init__(self, secrets=(), texts=(), choices=()):
        self.secret_values = list(secrets)
        self.texts = list(texts)
        self.choices = list(choices)
        self.secret_prompts: list[str] = []
        self.confirmations: list[str] = []

    def ask_text(self, label, default=""):
        return self.texts.pop(0) if self.texts else default

    def ask_choice(self, label, options, default=""):
        return self.choices.pop(0) if self.choices else default

    def ask_secret(self, name):
        self.secret_prompts.append(name)
        return self.secret_values.pop(0) if self.secret_values else ""

    def confirm(self, label, default=False):
        self.confirmations.append(label)
        return True


def _wire(monkeypatch, host, resolver, prompter=None, variable_writer=None, workflow_writer=None):
    context = SetupContext(
        source=FileTemplateSource(REPO_ROOT),
        refs=StaticRefResolver(PIN),
        host=host,
        resolver=resolver,
        variable_writer=variable_writer or FakeVariableWriter(),
        workflow_writer=workflow_writer or FakeWorkflowWriter(),
        broker_url=BROKER,
    )
    monkeypatch.setattr(cli, "build_setup", lambda **kwargs: context)
    if prompter is not None:
        monkeypatch.setattr(cli, "InitPrompter", lambda: prompter)
    return context


def _set_secrets(monkeypatch, **values):
    for name, value in values.items():
        monkeypatch.setenv(f"NEBUKO_SECRET_{name}", value)


def test_given_the_app_is_installed_when_init_runs_then_no_pat_prompt_appears(monkeypatch, capsys):
    host = FakeHost()
    prompter = FakePrompter(secrets=["key-123"], texts=["acme/widgets"], choices=["repository", "openrouter"])
    _wire(monkeypatch, host, FakeResolver(installed=True), prompter)

    assert cli.main([]) == 0

    assert "GH_PAT" not in prompter.secret_prompts
    assert host.secrets == {"OPENROUTER_API_KEY": "key-123"}
    assert "personal-access-tokens" not in capsys.readouterr().out


def test_given_the_app_is_installed_when_init_runs_then_no_broker_variable_is_written(monkeypatch):
    host = FakeHost()
    variables = FakeVariableWriter()
    _wire(monkeypatch, host, FakeResolver(installed=True), variable_writer=variables)
    _set_secrets(monkeypatch, OPENROUTER_API_KEY="key-123")

    assert cli.main(["--repo", "acme/widgets", "--non-interactive"]) == 0

    assert variables.values == {}  # the workflow falls back to the published broker


def test_given_the_app_is_installed_when_init_runs_then_the_caller_workflow_is_written(monkeypatch):
    host = FakeHost()
    workflow = FakeWorkflowWriter()
    _wire(monkeypatch, host, FakeResolver(installed=True), workflow_writer=workflow)
    _set_secrets(monkeypatch, OPENROUTER_API_KEY="key-123")

    assert cli.main(["--repo", "acme/widgets", "--non-interactive"]) == 0

    assert workflow.calls == [{"update": True, "dry_run": False}]


def test_given_the_app_is_not_installed_when_init_runs_then_the_app_install_is_requested(monkeypatch, capsys):
    host = FakeHost()
    prompter = FakePrompter(
        secrets=["key-123", "pat-456"], texts=["acme/widgets"], choices=["repository", "openrouter"]
    )
    _wire(monkeypatch, host, FakeResolver(installed=False), prompter)

    assert cli.main([]) == 2

    err = capsys.readouterr().err
    assert "https://github.com/apps/nebuko/installations/new" in err
    assert "--pat" in err
    assert prompter.secret_prompts == []  # nothing is asked before the guidance


def test_given_the_app_is_not_installed_when_init_runs_with_pat_then_the_pat_is_asked(monkeypatch):
    host = FakeHost()
    prompter = FakePrompter(
        secrets=["key-123", "pat-456"], texts=["acme/widgets"], choices=["repository", "openrouter"]
    )
    _wire(monkeypatch, host, FakeResolver(installed=False), prompter)

    assert cli.main(["--pat"]) == 0

    assert prompter.secret_prompts == ["OPENROUTER_API_KEY", "GH_PAT"]
    assert host.secrets == {"OPENROUTER_API_KEY": "key-123", "GH_PAT": "pat-456"}


def test_given_assume_app_when_init_runs_then_detection_is_skipped(monkeypatch):
    host = FakeHost()
    resolver = FakeResolver(installed=False)
    _wire(monkeypatch, host, resolver)
    _set_secrets(monkeypatch, OPENROUTER_API_KEY="key-123")

    assert cli.main(["--repo", "acme/widgets", "--non-interactive", "--assume-app"]) == 0

    assert resolver.probes == 0
    assert "GH_PAT" not in host.secrets


def test_given_assume_pat_when_init_runs_then_the_pat_is_asked_despite_the_app(monkeypatch):
    host = FakeHost()
    resolver = FakeResolver(installed=True)
    _wire(monkeypatch, host, resolver)
    _set_secrets(monkeypatch, OPENROUTER_API_KEY="key-123", GH_PAT="pat-456")

    assert cli.main(["--repo", "acme/widgets", "--non-interactive", "--pat"]) == 0

    assert resolver.probes == 0
    assert host.secrets["GH_PAT"] == "pat-456"


def test_given_broker_url_flag_when_init_runs_then_the_workflow_carries_it(monkeypatch):
    host = FakeHost()
    variables = FakeVariableWriter()
    context = _wire(monkeypatch, host, FakeResolver(installed=True), variable_writer=variables)
    _set_secrets(monkeypatch, OPENROUTER_API_KEY="key-123")
    monkeypatch.setattr(
        cli,
        "build_setup",
        lambda **kwargs: SetupContext(
            source=context.source,
            refs=context.refs,
            host=context.host,
            resolver=context.resolver,
            variable_writer=variables,
            workflow_writer=context.workflow_writer,
            broker_url=DEFAULT_BROKER_URL,
        ),
    )

    assert (
        cli.main(
            ["--repo", "acme/widgets", "--non-interactive", "--broker-url", "https://mine.example"]
        )
        == 0
    )

    assert variables.values == {}  # the flag no longer writes a repo variable


def test_given_dry_run_when_init_runs_then_the_workflow_writer_is_told(monkeypatch):
    host = FakeHost()
    workflow = FakeWorkflowWriter()
    _wire(monkeypatch, host, FakeResolver(installed=True), workflow_writer=workflow)
